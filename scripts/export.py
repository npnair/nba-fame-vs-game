"""Export the dbt mart to the web page (docs/data/fame.js) and to CSVs in results/."""

from __future__ import annotations

import json
import math
import sys
from datetime import date
from pathlib import Path

import duckdb
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
WAREHOUSE = ROOT / "warehouse.duckdb"
WEB_OUT = ROOT / "docs" / "data" / "fame.js"
RESULTS = ROOT / "results"
HISTORY_COLS = ["date", "bref_id", "player_name", "production_score", "fame_score", "gap", "quadrant", "verdict"]


def clean(value):
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return None
    if hasattr(value, "isoformat"):     # dates and timestamps -> YYYY-MM-DD
        return value.isoformat()[:10]
    if value is pd.NaT:
        return None
    if hasattr(value, "item"):          # numpy scalar
        return value.item()
    return value


def main() -> int:
    con = duckdb.connect(str(WAREHOUSE), read_only=True)
    df = con.execute("select * from fct_fame_vs_game order by gap desc").df()
    meta = con.execute("""
        select max(view_date) as pageviews_through,
               (select max(as_of) from stg_news) as news_as_of,
               (select max(as_of) from stg_social) as social_as_of,
               (select count(*) from stg_social where instagram_followers is not null) as instagram_filled,
               (select count(*) from stg_social where tiktok_followers is not null) as tiktok_filled
        from stg_pageviews
    """).df().iloc[0]
    con.close()
    if df.empty:
        print("The mart is empty; nothing exported.", file=sys.stderr)
        return 1

    today = date.today().isoformat()
    payload = {
        "generated": today,
        "pageviewsThrough": clean(meta.pageviews_through),
        "newsAsOf": clean(meta.news_as_of),
        "socialAsOf": clean(meta.social_as_of),
        "instagramFilled": int(meta.instagram_filled),
        "tiktokFilled": int(meta.tiktok_filled),
        "players": [{k: clean(v) for k, v in row.items()} for row in df.to_dict(orient="records")],
    }
    WEB_OUT.parent.mkdir(parents=True, exist_ok=True)
    WEB_OUT.write_text(
        "// Generated by scripts/export.py from the dbt mart fct_fame_vs_game. Do not edit by hand.\n"
        f"window.FAME_DATA = {json.dumps(payload, indent=1, ensure_ascii=False)};\n", encoding="utf-8")

    RESULTS.mkdir(exist_ok=True)
    df.to_csv(RESULTS / "fame_vs_game.csv", index=False)

    history_path = RESULTS / "history.csv"
    snap = df.assign(date=today)[HISTORY_COLS]
    if history_path.exists():
        old = pd.read_csv(history_path, dtype={"bref_id": str})
        snap = pd.concat([old[old.date != today], snap], ignore_index=True)
    snap.to_csv(history_path, index=False)

    print(f"Exported {len(df)} players to {WEB_OUT.relative_to(ROOT)} and results/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
